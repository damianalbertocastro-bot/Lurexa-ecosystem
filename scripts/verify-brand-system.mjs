import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const failures = [];
const pass = (message) => console.log(`✓ ${message}`);
const fail = (message) => failures.push(message);
const read = (relative) => fs.readFileSync(path.join(root, relative), "utf8");
const exists = (relative) => fs.existsSync(path.join(root, relative));

function walk(relativeDir) {
  const absolute = path.join(root, relativeDir);
  if (!fs.existsSync(absolute)) return [];
  return fs.readdirSync(absolute, { withFileTypes: true }).flatMap((entry) => {
    const relative = path.join(relativeDir, entry.name);
    if (entry.isDirectory()) return walk(relative);
    return relative;
  });
}

const currentProducts = ["learn", "coach", "teach", "admin", "insight", "studio"];
const currentMarks = currentProducts.map((id) => `packages/ui/brand/marks/lurexa-${id}.svg`);
const layerMarks = ["packages/ui/brand/marks/lurexa-core.svg", "packages/ui/brand/marks/lurexa-mind.svg"];
const supportMarks = ["packages/ui/brand/marks/lurexa-master.svg", "packages/ui/brand/marks/lurexa-docs.svg"];
const futureCommunityMark = "packages/ui/brand/concepts/lurexa-community-concept.svg";

for (const mark of [...currentMarks, ...layerMarks, ...supportMarks, futureCommunityMark]) {
  if (!exists(mark)) fail(`Missing canonical mark: ${mark}`);
}
if (failures.length === 0) pass("canonical current, layer, surface, and Community concept marks exist");

const registry = read("packages/config/src/product-registry.ts");
for (const id of currentProducts) {
  const displayName = id[0].toUpperCase() + id.slice(1);
  if (!registry.includes(`id: "${id}"`) || !registry.includes(`name: "Lurexa ${displayName}"`)) {
    fail(`Current product registry entry is missing or malformed: ${id}`);
  }
}
if (!registry.includes('name: "Lurexa Community"') || !registry.includes('classification: "future-product-concept"')) {
  fail("Community must remain classified as a future-product-concept");
} else {
  pass("Community remains future-product-concept, not a current product");
}

const urlContract = read("packages/config/src/product-urls.ts");
const requiredUrlVariables = [
  "NEXT_PUBLIC_LUREXA_ECOSYSTEM_URL",
  "NEXT_PUBLIC_LUREXA_LEARN_URL",
  "NEXT_PUBLIC_LUREXA_TEACHER_URL",
  "NEXT_PUBLIC_LUREXA_COACH_URL",
  "NEXT_PUBLIC_LUREXA_TEACH_URL",
  "NEXT_PUBLIC_LUREXA_ADMIN_URL",
  "NEXT_PUBLIC_LUREXA_INSIGHT_URL",
  "NEXT_PUBLIC_LUREXA_STUDIO_URL",
  "NEXT_PUBLIC_LUREXA_DOCS_URL",
];
const reservedFutureVariables = ["NEXT_PUBLIC_LUREXA_COMMUNITY_URL"];
const allowedUrlVariables = new Set([...requiredUrlVariables, ...reservedFutureVariables]);

for (const variable of requiredUrlVariables) {
  if (!urlContract.includes(variable)) fail(`URL contract missing ${variable}`);
}
if (!urlContract.includes('community: "NEXT_PUBLIC_LUREXA_COMMUNITY_URL"')) {
  fail("Reserved Community URL variable is not documented in the typed contract");
} else {
  pass("cross-product public URL names are centralized");
}

const sourceFiles = walk("apps").filter((file) => /\.(?:ts|tsx|js|jsx|mjs|cjs)$/.test(file));
for (const file of sourceFiles) {
  const content = read(file);
  const matches = content.match(/NEXT_PUBLIC_LUREXA_[A-Z_]+/g) ?? [];
  for (const variable of matches) {
    if (!allowedUrlVariables.has(variable)) fail(`${file} uses undocumented public URL variable ${variable}`);
    if (reservedFutureVariables.includes(variable)) fail(`${file} activates reserved future URL variable ${variable}`);
  }
}
if (!failures.some((item) => item.includes("undocumented public URL") || item.includes("reserved future URL"))) {
  pass("app URL consumers use only documented active variables");
}

const shellExpectations = [
  ["apps/web/app/layout.tsx", "Lurexa Learning Technologies"],
  ["apps/learn-web/app/layout.tsx", "Lurexa Learn"],
  ["apps/teach-web/app/layout.tsx", "Lurexa Teach"],
  ["apps/admin-portal/app/layout.tsx", "Lurexa Admin"],
  ["apps/docs/app/layout.tsx", "Lurexa Docs"],
];
for (const [file, expected] of shellExpectations) {
  const content = read(file);
  if (content.includes("Create Next App") || content.includes("Generated by create next app")) {
    fail(`${file} still contains starter metadata`);
  }
  if (!content.includes(expected)) fail(`${file} does not identify the expected Lurexa surface: ${expected}`);
}
if (!failures.some((item) => item.includes("layout.tsx"))) pass("current web shells expose canonical product/company metadata");

const shellDirectories = [
  "apps/web/app",
  "apps/learn-web/app",
  "apps/teach-web/app",
  "apps/admin-portal/app",
  "apps/docs/app",
];
for (const directory of shellDirectories) {
  const icon = `${directory}/icon.svg`;
  const legacyFavicon = `${directory}/favicon.ico`;
  if (!exists(icon)) fail(`Missing canonical shell icon: ${icon}`);
  if (exists(legacyFavicon)) fail(`Legacy favicon conflicts with canonical shell icon: ${legacyFavicon}`);
}
if (!failures.some((item) => item.includes("shell icon") || item.includes("favicon"))) pass("current web shells have one canonical browser icon source");

const sizeContract = read("packages/ui/src/brand-mark-size.ts");
for (const size of ["sm", "md", "lg"]) {
  if (!sizeContract.includes(`${size}: {`)) fail(`Semantic brand mark size is missing: ${size}`);
}
for (const component of ["MasterMark.tsx", "ProductMark.tsx", "DocsMark.tsx", "EcosystemLayerMark.tsx"]) {
  const content = read(`packages/ui/src/${component}`);
  if (!content.includes("size?: BrandMarkSize")) fail(`${component} does not expose the shared semantic size contract`);
  if (!content.includes("brandMarkSizeClasses[size]")) fail(`${component} bypasses shared semantic size classes`);
}
if (!failures.some((item) => item.includes("Semantic brand mark") || item.includes("semantic size"))) pass("shared mark components use one sm/md/lg sizing contract");

const relatedExperiences = read("packages/ui/src/RelatedExperiences.tsx");
if (relatedExperiences.includes('| "community"') || relatedExperiences.includes('kind === "community"')) {
  fail("RelatedExperiences uses ambiguous community identity; use teach-community until Lurexa Community activates");
} else if (!relatedExperiences.includes('"teach-community"')) {
  fail("RelatedExperiences is missing explicit Teach Community identity");
} else {
  pass("Teach Community is visually distinct from future Lurexa Community");
}

for (const file of ["apps/mobile/app/(student)/learn.tsx", "apps/mobile/app/(student)/tutor.tsx"]) {
  const content = read(file);
  if (!content.includes("Lurexa") || !content.includes("Learn")) fail(`${file} does not expose Lurexa Learn identity`);
}
if (!failures.some((item) => item.includes("apps/mobile"))) pass("mobile learner surfaces expose Lurexa Learn identity");

const deployment = read("deployment/products.json");
if (/community/i.test(deployment)) fail("Community must not appear in current deployment/products.json before activation");
else pass("Community is absent from active deployment topology");

const webPage = read("apps/web/app/page.tsx");
if (webPage.includes('"community"') || webPage.includes("Lurexa Community")) {
  fail("Community must not appear in the current ecosystem product navigation before activation");
} else {
  pass("Community is absent from current ecosystem product navigation");
}

// The ecosystem homepage serves static copies of the product marks so their
// appearance does not depend on consumer Tailwind output. Keep those copies
// aligned with the canonical UI assets and make the page reference each one.
for (const id of currentProducts) {
  const canonicalPath = `packages/ui/brand/marks/lurexa-${id}.svg`;
  const publicPath = `apps/web/public/brand/lurexa-${id}.svg`;
  if (!exists(publicPath)) {
    fail(`Missing ecosystem public product mark: ${publicPath}`);
    continue;
  }

  const normalizeSvg = (value) => value.replace(/\s+/g, "");
  if (normalizeSvg(read(canonicalPath)) !== normalizeSvg(read(publicPath))) {
    fail(`Ecosystem public product mark diverges from canonical asset: ${id}`);
  }
  if (!webPage.includes(`/brand/lurexa-${id}.svg`)) {
    fail(`Ecosystem homepage does not reference its public product mark: ${id}`);
  }
}
if (!failures.some((item) => item.includes("public product mark") || item.includes("homepage does not reference"))) {
  pass("ecosystem public product marks are canonical and referenced by the landing page");
}

if (!exists("apps/docs/app/brand/page.tsx")) fail("Missing local brand visual QA route at apps/docs/app/brand/page.tsx");
else {
  const qaPage = read("apps/docs/app/brand/page.tsx");
  if (!qaPage.includes('size="sm"') || !qaPage.includes('size="md"') || !qaPage.includes('size="lg"')) {
    fail("Local Docs brand QA route must exercise all semantic mark sizes");
  } else {
    pass("local Docs brand visual QA route covers semantic sizes");
  }
}

if (failures.length) {
  console.error("\nBrand-system verification failed:");
  for (const message of failures) console.error(`- ${message}`);
  process.exit(1);
}

console.log("\nLurexa brand-system verification passed.");
